def fake_sha():
    return hashlib.sha1(os.urandom(20)).hexdigest()


def git(repo, *args):
    return subprocess.run(
        ["git", "-c", "commit.gpgsign=false", "-c", "tag.gpgsign=false"]
        + list(args),
        capture_output=True, text=True, cwd=repo,
    )


def init_repo(repo, gitattributes=None):
    git(repo, "init", "-b", "main")
    git(repo, "config", "user.email", "test@test.com")
    git(repo, "config", "user.name", "Test")
    git(repo, "config", "commit.gpgsign", "false")
    if gitattributes:
        with open(os.path.join(repo, ".gitattributes"), "w") as f:
            f.write(gitattributes)


def generate_lockfile(workflows, pool):
    """Generate a lockfile matching gh actions-pin output format."""
    lines = [
        "# This file is machine-generated by `gh actions-pin`.",
        "# Do not edit by hand; run `gh actions-pin` to update.",
        "# Docs: https://gh.io/actions-lockfile",
        "version: v0.0.1",
        "actions:",
    ]
    all_refs = set()
    for deps in workflows.values():
        all_refs.update(deps)
    for ref_str in sorted(all_refs):
        sha = pool[ref_str]
        oid = abs(hash(ref_str.split("/")[0])) % 100000000
        rid = abs(hash(ref_str.split("@")[0])) % 1000000000
        tag = ref_str.split("@")[1]
        branch = f"releases/{tag.split('.')[0]}" if "." in tag else tag
        lines += [
            f"    {ref_str}:sha1-{sha}:",
            f"        tag: {tag}",
            f"        branch: {branch}",
            f"        commit: sha1-{sha}",
            f"        owner_id: {oid}",
            f"        repo_id: {rid}",
        ]
    lines.append("workflows:")
    for wf_path in sorted(workflows.keys()):
        lines.append(f"    {wf_path}:")
        lines.append(f"        dependencies:")
        for dep in sorted(workflows[wf_path]):
            sha = pool[dep]
            lines.append(f"            - {dep}:sha1-{sha}")
    return "\n".join(lines) + "\n"


def generate_per_wf_lockfile(wf_name, deps, pool):
    lines = [f"# Lockfile for {wf_name}", "version: v0.0.1", "dependencies:"]
    for dep in sorted(deps):
        sha = pool[dep]
        lines += [f"    {dep}:sha1-{sha}:", f"        commit: sha1-{sha}"]
    return "\n".join(lines) + "\n"


def gen_base(n, rng):
    wfs, pool, refs = {}, {}, {}
    for action in ALL_ACTIONS:
        ref = (
            "main"
            if action.startswith("myorg")
            else f"v{rng.randint(3,5)}.{rng.randint(0,9)}.{rng.randint(0,5)}"
        )
        refs[action] = ref
        pool[f"{action}@{ref}"] = fake_sha()
    for i in range(1, n + 1):
        path = f".github/workflows/wf-{i:03d}.yml"
        chosen = rng.sample(ALL_ACTIONS, rng.randint(2, 6))
        if "actions/checkout" not in chosen:
            chosen[0] = "actions/checkout"
        wfs[path] = [f"{a}@{refs[a]}" for a in chosen]
    return wfs, pool, refs


