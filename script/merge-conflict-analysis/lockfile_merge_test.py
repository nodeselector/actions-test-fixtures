@dataclass
class Result:
    name: str
    desc: str
    conflict: bool
    markers: int = 0
    conflict_files: list = field(default_factory=list)


def write_state(repo, wfs, pool):
    wf_dir = os.path.join(repo, ".github", "workflows")
    os.makedirs(wf_dir, exist_ok=True)
    for f in os.listdir(wf_dir):
        if f.endswith(".yml"):
            os.remove(os.path.join(wf_dir, f))
    with open(os.path.join(wf_dir, "actions.lock"), "w") as f:
        f.write(generate_lockfile(wfs, pool))
    for path, deps in wfs.items():
        full = os.path.join(repo, path)
        with open(full, "w") as f:
            f.write(
                f"name: {os.path.basename(path)}\non: push\njobs:\n"
                f"  build:\n    runs-on: ubuntu-latest\n    steps:\n"
            )
            for d in deps:
                f.write(f"      - uses: {d}\n")


def write_state_per_wf(repo, wfs, pool):
    wf_dir = os.path.join(repo, ".github", "workflows")
    os.makedirs(wf_dir, exist_ok=True)
    for f in os.listdir(wf_dir):
        os.remove(os.path.join(wf_dir, f))
    for path, deps in wfs.items():
        full = os.path.join(repo, path)
        wf_name = os.path.basename(path)
        with open(full, "w") as f:
            f.write(
                f"name: {wf_name}\non: push\njobs:\n"
                f"  build:\n    runs-on: ubuntu-latest\n    steps:\n"
            )
            for d in deps:
                f.write(f"      - uses: {d}\n")
        lock_path = full.replace(".yml", ".lock")
        with open(lock_path, "w") as f:
            f.write(generate_per_wf_lockfile(wf_name, deps, pool))


def run_global_scenario(name, desc, base_wfs, base_pool, refs, mutate_a, mutate_b,
                        gitattributes=None):
    repo = tempfile.mkdtemp(prefix="lf-")
    init_repo(repo, gitattributes=gitattributes)

    write_state(repo, base_wfs, base_pool)
    git(repo, "add", "-A")
    r = git(repo, "commit", "-m", "base")
    if r.returncode != 0:
        shutil.rmtree(repo)
        return None

    git(repo, "checkout", "-b", "branch-a", "main")
    wfs_a = {k: list(v) for k, v in base_wfs.items()}
    pool_a = dict(base_pool)
    mutate_a(wfs_a, pool_a, refs)
    write_state(repo, wfs_a, pool_a)
    git(repo, "add", "-A")
    git(repo, "commit", "-m", "branch-a")

    git(repo, "checkout", "-b", "branch-b", "main")
    wfs_b = {k: list(v) for k, v in base_wfs.items()}
    pool_b = dict(base_pool)
    mutate_b(wfs_b, pool_b, refs)
    write_state(repo, wfs_b, pool_b)
    git(repo, "add", "-A")
    git(repo, "commit", "-m", "branch-b")

    git(repo, "checkout", "branch-a")
    merge = git(repo, "merge", "branch-b", "--no-edit")

    conflict = merge.returncode != 0
    markers = 0
    conflict_files = []
    if conflict:
        lp = os.path.join(repo, ".github", "workflows", "actions.lock")
        if os.path.exists(lp):
            with open(lp) as f:
                markers = f.read().count("<<<<<<<")
        ls = git(repo, "diff", "--name-only", "--diff-filter=U")
        conflict_files = [l.strip() for l in ls.stdout.strip().split("\n") if l.strip()]
        git(repo, "merge", "--abort")

    shutil.rmtree(repo)
    return Result(name, desc, conflict, markers, conflict_files)


def run_per_wf_scenario(name, desc, base_wfs, base_pool, refs, mutate_a, mutate_b):
    repo = tempfile.mkdtemp(prefix="lf-pw-")
    init_repo(repo)

    write_state_per_wf(repo, base_wfs, base_pool)
    git(repo, "add", "-A")
    r = git(repo, "commit", "-m", "base")
    if r.returncode != 0:
        shutil.rmtree(repo)
        return None

    for branch, mutate in [("branch-a", mutate_a), ("branch-b", mutate_b)]:
        git(repo, "checkout", "-b", branch, "main")
        wfs = {k: list(v) for k, v in base_wfs.items()}
        pl = dict(base_pool)
        mutate(wfs, pl, refs)
        write_state_per_wf(repo, wfs, pl)
        for p in set(base_wfs) - set(wfs):
            for ext in [".yml", ".lock"]:
                fp = os.path.join(repo, p.replace(".yml", ext))
                if os.path.exists(fp):
                    os.remove(fp)
        git(repo, "add", "-A")
        git(repo, "commit", "-m", branch)

    git(repo, "checkout", "branch-a")
    merge = git(repo, "merge", "branch-b", "--no-edit")
    conflict = merge.returncode != 0
    conflict_files = []
    if conflict:
        ls = git(repo, "diff", "--name-only", "--diff-filter=U")
        conflict_files = [l.strip() for l in ls.stdout.strip().split("\n") if l.strip()]
        git(repo, "merge", "--abort")

    shutil.rmtree(repo)
    return Result(name, desc, conflict, 0, conflict_files)


# ---------------------------------------------------------------------------
# Print helpers
# ---------------------------------------------------------------------------


def print_header(title):
    print(f"\n{'='*80}")
    print(f"  {title}")
    print(f"{'='*80}\n")


def print_result(r):
    if r is None:
        print("  ⚠️  scenario failed to run")
        return
    icon = "❌" if r.conflict else "✅"
    suffix = ""
    if r.conflict:
        lf_files = [f for f in r.conflict_files if "actions.lock" in f or ".lock" in f]
        wf_files = [f for f in r.conflict_files if f not in lf_files]
        parts = []
        if r.markers:
            parts.append(f"{r.markers} marker(s) in lockfile")
        elif lf_files:
            parts.append(f"{len(lf_files)} lockfile(s)")
        if wf_files:
            parts.append(f"{len(wf_files)} workflow file(s)")
        suffix = f" — {', '.join(parts)}" if parts else ""
    print(f"  {icon} {r.name}{suffix}")
    if r.desc:
        print(f"     {r.desc}")


def print_summary(results, label=""):
    valid = [r for r in results if r is not None]
    clean = sum(1 for r in valid if not r.conflict)
    total = len(valid)
    pct = clean / total * 100 if total else 0
    print(f"\n  {label}Clean: {clean}/{total} ({pct:.0f}%)")


