def run_stress_tests():
    """100 workflows with wf-NNN naming — worst case for sort collisions."""
    print_header("STRESS TEST — 100 workflows, sequential names (worst case)")

    rng = random.Random(42)
    base_wfs, base_pool, refs = gen_base(100, rng)
    base_lines = len(generate_lockfile(base_wfs, base_pool).split("\n"))
    print(f"  Base: 100 workflows, {base_lines} line lockfile\n")

    scenarios = [
        ("disjoint-adds", "A adds wf 101-105, B adds wf 106-110",
         lambda w, p, r: add_wfs(w, p, r, range(101, 106)),
         lambda w, p, r: add_wfs(w, p, r, range(106, 111))),
        ("disjoint-repins", "A re-pins wf 1-10, B re-pins wf 50-60",
         lambda w, p, r: repin_wfs(w, p, range(1, 11)),
         lambda w, p, r: repin_wfs(w, p, range(50, 61))),
        ("same-action-repin", "Both re-pin actions/checkout → different SHAs",
         lambda w, p, r: repin_action(w, p, "actions/checkout"),
         lambda w, p, r: repin_action(w, p, "actions/checkout")),
        ("mixed-realistic", "A: +3wf repin 5 | B: +2wf -3wf repin 3",
         lambda w, p, r: (add_wfs(w, p, r, range(101, 104)), repin_wfs(w, p, range(1, 6))),
         lambda w, p, r: (add_wfs(w, p, r, range(104, 106)),
                          delete_wfs(w, [20, 30, 40]), repin_wfs(w, p, range(60, 63)))),
        ("overlapping-deletes", "A dels wf 10,20,30,40,50 | B dels wf 30,40,50,60,70",
         lambda w, p, r: delete_wfs(w, [10, 20, 30, 40, 50]),
         lambda w, p, r: delete_wfs(w, [30, 40, 50, 60, 70])),
        ("different-upgrades", "A upgrades checkout→v5, B upgrades setup-node→v5",
         lambda w, p, r: upgrade(w, p, "actions/checkout", r, "v5.0.0"),
         lambda w, p, r: upgrade(w, p, "actions/setup-node", r, "v5.0.0")),
        ("both-add-same-wf", "Both add wf-101 with different deps",
         lambda w, p, r: add_wfs(w, p, r, [101]),
         lambda w, p, r: add_wfs(w, p, r, [101])),
        ("massive-repin", "A re-pins ALL actions, B adds 10 new wfs",
         lambda w, p, r: [p.__setitem__(k, fake_sha()) for k in list(p.keys())],
         lambda w, p, r: add_wfs(w, p, r, range(101, 111))),
    ]

    results = []
    for name, desc, fn_a, fn_b in scenarios:
        r = run_global_scenario(name, desc, base_wfs, base_pool, refs, fn_a, fn_b)
        results.append(r)
        print_result(r)

    print_summary(results)
    return results


