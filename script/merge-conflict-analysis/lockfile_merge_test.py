def add_wfs(wfs, pool, refs, ids):
    for i in ids:
        path = f".github/workflows/wf-{i:03d}.yml"
        chosen = random.sample(ALL_ACTIONS, 3)
        if "actions/checkout" not in chosen:
            chosen[0] = "actions/checkout"
        for a in chosen:
            ref = refs.get(a, "v4.0.0")
            key = f"{a}@{ref}"
            if key not in pool:
                pool[key] = fake_sha()
        wfs[path] = [f"{a}@{refs.get(a, 'v4.0.0')}" for a in chosen]


def repin_wfs(wfs, pool, ids):
    for i in ids:
        path = f".github/workflows/wf-{i:03d}.yml"
        if path in wfs:
            for dep in wfs[path]:
                pool[dep] = fake_sha()


def repin_action(wfs, pool, prefix):
    for key in list(pool.keys()):
        if key.startswith(prefix + "@"):
            pool[key] = fake_sha()


def upgrade(wfs, pool, action, refs, new_ver):
    old_ref = refs.get(action)
    if not old_ref:
        return
    old_key = f"{action}@{old_ref}"
    new_key = f"{action}@{new_ver}"
    pool[new_key] = fake_sha()
    for path in wfs:
        wfs[path] = [new_key if d == old_key else d for d in wfs[path]]


def delete_wfs(wfs, ids):
    for i in ids:
        wfs.pop(f".github/workflows/wf-{i:03d}.yml", None)


