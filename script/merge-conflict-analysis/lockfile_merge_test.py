def run_union_merge_tests():
    """Test .gitattributes merge=union strategy."""
    print_header("UNION MERGE STRATEGY — .gitattributes merge=union")
    print("  ⚠️  Union merge avoids conflicts but may produce semantically")
    print("  invalid output (duplicate keys with different SHAs).\n")

    rng = random.Random(42)
    base_wfs, base_pool, refs = gen_base(100, rng)
    gitattr = ".github/workflows/actions.lock merge=union\n"

    scenarios = [
        ("disjoint-adds", "A adds wf 101-105, B adds wf 106-110",
         lambda w, p, r: add_wfs(w, p, r, range(101, 106)),
         lambda w, p, r: add_wfs(w, p, r, range(106, 111))),
        ("same-action-repin", "Both re-pin checkout → different SHAs",
         lambda w, p, r: repin_action(w, p, "actions/checkout"),
         lambda w, p, r: repin_action(w, p, "actions/checkout")),
        ("mixed-realistic", "A: +3wf repin 5 | B: +2wf -3wf repin 3",
         lambda w, p, r: (add_wfs(w, p, r, range(101, 104)), repin_wfs(w, p, range(1, 6))),
         lambda w, p, r: (add_wfs(w, p, r, range(104, 106)),
                          delete_wfs(w, [20, 30, 40]), repin_wfs(w, p, range(60, 63)))),
        ("massive-repin", "A re-pins ALL, B adds 10 wfs",
         lambda w, p, r: [p.__setitem__(k, fake_sha()) for k in list(p.keys())],
         lambda w, p, r: add_wfs(w, p, r, range(101, 111))),
    ]

    results = []
    for name, desc, fn_a, fn_b in scenarios:
        r = run_global_scenario(name, desc, base_wfs, base_pool, refs,
                                fn_a, fn_b, gitattributes=gitattr)
        results.append(r)
        print_result(r)

    print_summary(results, "Union merge — ")
    return results


